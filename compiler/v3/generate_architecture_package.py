def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()

def define(name: str, value: int, width: int | None = None) -> str:
    encoded = str(value) if width is None else f"{width}'d{value}"
    return f"`define {name:<48} {encoded}"

def enum_lines(prefix: str, enum_type: type[IntEnum], width: int) -> list[str]:
    return [define(f"RECON_{prefix}_{item.name}", int(item), width) for item in enum_type]


def field_lines(prefix: str, layout: dict[str, isa.Field]) -> list[str]:
    lines = []
    for name, field in layout.items():
        field_name = f"RECON_{prefix}_FIELD_{name.upper()}"
        lines.extend([
            define(f"{field_name}_LSB", field.lsb),
            define(f"{field_name}_W", field.width),
        ])
    return lines

