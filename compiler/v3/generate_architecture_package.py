def context_defs() -> str:
    lines = ["`ifndef CONTEXT_ISA_DEFS_VH", "`define CONTEXT_ISA_DEFS_VH",
             f"// Generated context ISA revision {isa.CONTEXT_FORMAT_REVISION}. Do not edit."]
    for prefix, enum_type, width in (
        ("TILE_OP", isa.TileOperation, 5),
        ("OPERAND_SOURCE", isa.OperandSource, 3),
        ("ROUTE_SOURCE", isa.RouteSource, 3),
        ("NEXT_PC_MODE", isa.NextPcMode, 3),
        ("PHASE_OP", isa.PhaseOperation, 3),
        ("PHASE_CONDITION", isa.PhaseCondition, 4),
        ("EXTERNAL_STREAM_SOURCE", isa.ExternalStreamSource, 2),
        ("PHI_COMMAND", isa.PhiStreamCommand, 2),
        ("RESOURCE_OP", isa.ResourceOperation, 5),
        ("RESOURCE_INPUT", isa.ResourceInput, 3),
        ("RESOURCE_OUTPUT", isa.ResourceOutput, 3),
        ("LOOP_LIMIT", isa.LoopLimitSource, 4),
        ("RESOURCE_COUNT", isa.ResourceCountSource, 4),
        ("STREAM_BOUNDARY", isa.StreamBoundary, 2),
        ("ELEMENT_FORMAT", isa.ElementFormat, 3),
        ("MEMORY_SPACE", isa.MemorySpace, 2),
        ("BANK_MODE", isa.BankMode, 3),
        ("PACKING_MODE", isa.PackingMode, 3)):
        lines.extend(enum_lines(prefix, enum_type, width))
    for prefix, layout in (
        ("TILE", isa.TILE_FIELDS),
        ("ARRAY_CONTROL", isa.ARRAY_CONTROL_FIELDS),
        ("STREAM", isa.STREAM_FIELDS),
        ("PHASE", isa.PHASE_FIELDS),
        ("RESOURCE", isa.RESOURCE_FIELDS),
        ("MEMORY_CONFIGURATION", isa.MEMORY_CONFIGURATION_FIELDS),
    ):
        lines.extend(field_lines(prefix, layout))
    lines.extend(["`endif", ""])
    return "\n".join(lines)


def architecture_guard_defs() -> str:
    configuration = architecture.load()
    errors = configuration["reservation_guard"]["error_codes"]
    tile_mask = sum(1 << int(item) for item in isa.TileOperation)
    resource_mask = sum(1 << int(item) for item in isa.ResourceOperation)
    implemented_resource_mask = sum(
        1 << record["code"] for record in configuration["resource_operations"]
        if record["status"] == "implemented")
    reserved_fault_mask = sum(
        1 << record["code"] for record in configuration["resource_operations"]
        if record["status"] == "reserved")
    route_mask = sum(1 << int(item) for item in isa.RouteSource
                     if item != isa.RouteSource.ROW_OR_COLUMN_EXPRESS)
    next_pc_mask = sum(1 << int(item) for item in isa.NextPcMode)
    phase_operation_mask = sum(1 << int(item) for item in isa.PhaseOperation)
    phase_condition_mask = sum(1 << int(item) for item in isa.PhaseCondition)
    execution = configuration["execution_context"]
    lines = [
        "`ifndef ARCHITECTURE_GUARD_DEFS_VH",
        "`define ARCHITECTURE_GUARD_DEFS_VH",
        "// Generated from architecture_configuration.json. Do not edit.",
        f"`define RECON_ARCHITECTURE_HASH 256'h{architecture.configuration_hash(configuration)}",
        f"`define RECON_TILE_OPERATION_LEGAL_MASK 32'h{tile_mask:08x}",
        f"`define RECON_RESOURCE_OPERATION_LEGAL_MASK 32'h{resource_mask:08x}",
        f"`define RECON_RESOURCE_OPERATION_IMPLEMENTED_MASK 32'h{implemented_resource_mask:08x}",
        f"`define RECON_RESOURCE_OPERATION_RESERVED_FAULT_MASK 32'h{reserved_fault_mask:08x}",
        f"`define RECON_ROUTE_SOURCE_LEGAL_MASK 8'h{route_mask:02x}",
        f"`define RECON_NEXT_PC_MODE_LEGAL_MASK 8'h{next_pc_mask:02x}",
        f"`define RECON_PHASE_OPERATION_LEGAL_MASK 8'h{phase_operation_mask:02x}",
        f"`define RECON_PHASE_CONDITION_LEGAL_MASK 16'h{phase_condition_mask:04x}",
        define("RECON_PHASE_ENTRY_PC", execution["phase_entry_pc"], 8),
    ]
    for name, code in errors.items():
        lines.append(define(f"RECON_CONTEXT_ERROR_{name.upper()}", code, 8))
    lines.extend(["`endif", ""])
    return "\n".join(lines)

def run_configuration_defs() -> str:
    lines = ["`ifndef RUN_CONFIGURATION_DEFS_VH", "`define RUN_CONFIGURATION_DEFS_VH",
             f"// Generated run-configuration block revision {run_configuration.REVISION}. Do not edit.",
             define("RECON_RUN_CONFIGURATION_MAGIC", run_configuration.MAGIC, 16),
             define("RECON_RUN_CONFIGURATION_WORDS", run_configuration.WORD_COUNT),
             define("RECON_RUN_CONFIGURATION_BYTES", run_configuration.BYTE_COUNT),
             define("RECON_RUN_CONFIGURATION_BITS", run_configuration.WORD_COUNT * 32)]
    lines.append(define("RECON_PHI_DATA_NORMALIZER_MAX_EXPONENT",
                        run_configuration.PHI_DATA_NORMALIZER_MAX_EXPONENT))
    lines.extend(enum_lines("REFINEMENT_PROFILE", run_configuration.RefinementProfile, 2))
    lines.extend(enum_lines("MATRIX_KIND", run_configuration.MatrixKind, 2))
    lines.extend(enum_lines("RESULT_MODE", run_configuration.ResultMode, 2))
    lines.extend(enum_lines("TERMINATION_MODE", run_configuration.TerminationMode, 1))
    lines.extend(["`define RECON_RUN_CONFIGURATION_W2_REFINEMENT_PROFILE_MSB 31",
                  "`define RECON_RUN_CONFIGURATION_W2_REFINEMENT_PROFILE_LSB 30",
                  "`define RECON_RUN_CONFIGURATION_W2_TERMINATION_MODE_MSB 29",
                  "`define RECON_RUN_CONFIGURATION_W2_TERMINATION_MODE_LSB 29",
                  "`endif", ""])
    return "\n".join(lines)

def disassembly() -> str:
    configuration = architecture.load()
    reserved = {
        record["name"] for record in configuration["resource_operations"]
        if record["status"] == "reserved"
    }
    tile = "\n".join(f"| {int(x)} | `{x.name}` |" for x in isa.TileOperation)
    resource = "\n".join(
        f"| {int(x)} | `{x.name}{'_RESERVED' if x.name in reserved else ''}` |"
        for x in isa.ResourceOperation)
    return (f"# Context ISA revision {isa.CONTEXT_FORMAT_REVISION} generated disassembly\n\n"
            "Undefined tile encoding 16 is the illegal retired multiply opcode.\n\n"
            "## Tile operations\n\n| Code | Operation |\n| ---: | --- |\n" + tile
            + "\n\n## Shared resource operations\n\n| Code | Operation |\n| ---: | --- |\n"
            + resource + "\n")

def transaction_golden() -> dict:
    segments = dict(context_compiler.restricted_refinement_resource_segments())
    certificate_path = [
        ("forward_Ap", isa.ResourceContext()),
        *segments["restricted_refinement_pre_transpose"],
        ("transpose_ATr", isa.ResourceContext()),
        *segments["restricted_refinement_certificate"],
    ]
    continuation_tail = segments["restricted_refinement_continuation"]

    def encode(sequence: list[tuple[str, isa.ResourceContext]]) -> list[dict]:
        encoded = []
        for cycle, (stage, resource) in enumerate(sequence):
            final = cycle == len(sequence) - 1
            control = isa.ArrayControlContext(
                next_pc=cycle + 1 if not final else 0,
                next_pc_mode=(isa.NextPcMode.SEQUENTIAL if not final
                              else isa.NextPcMode.RETURN_TO_PHASE),
                loop_limit_select=isa.LoopLimitSource.REFINEMENT_ITERATION_LIMIT,
                cluster_enable_mask=0b11, routine_done=int(final),
                safe_abort_point=int(final),
                guaranteed_commit=int(resource.operation == isa.ResourceOperation.NOP),
            )
            isa.validate_context_bundle(control, isa.StreamContext(), resource)
            encoded.append({"cycle": cycle, "stage": stage,
                            "array_control_word": isa.pack_array_control(control),
                            "resource_word": isa.pack_resource(resource)})
        return encoded

    cycles = encode(certificate_path)
    continuation = encode(continuation_tail)
    return {
        "schema": "cscgra-v3-context-transaction-golden-v2",
        "context_revision": isa.CONTEXT_FORMAT_REVISION,
        "routine": "restricted_refinement_iteration",
        "resource_control": "compiler_scheduled_implemented_resources_only",
        "blocked_stages": [],
        "cycles": cycles,
        "continuation_tail": continuation,
        "scalar_register_contract": {
            "certificate_entry": {"rf0": "gamma_reference", "rf1": "gamma_new"},
            "continuation_beta": "RF1/RF0 -> RF0",
            "continuation_rotate": "M5 gamma shadow restores gamma_new -> RF0 after update_p",
        },
    }

def generate() -> None:
    include = ROOT / "rtl" / "v3" / "include"
    reports = ROOT / "reports" / "v3"
    include.mkdir(parents=True, exist_ok=True)
    reports.mkdir(parents=True, exist_ok=True)
    configuration = architecture.load()
    compiled_contexts = context_compiler.payload()
    outputs = {
        include / "architecture_parameters.vh": architecture_parameters(),
        include / "context_isa_defs.vh": context_defs(),
        include / "architecture_guard_defs.vh": architecture_guard_defs(),
        include / "run_configuration_defs.vh": run_configuration_defs(),
        reports / "context_isa_disassembly.md": disassembly(),
        reports / "architecture_scaling.json": json.dumps(scaling.payload(), indent=2, sort_keys=True) + "\n",
        reports / "reconstruction_graphs.json": json.dumps(graphs.payload(), indent=2, sort_keys=True) + "\n",
        reports / "context_transaction_golden.json": json.dumps(
            transaction_golden(), indent=2, sort_keys=True) + "\n",
        reports / "architecture_latency_ii.json": json.dumps(
            architecture.latency_ii_payload(configuration), indent=2,
            sort_keys=True) + "\n",
        reports / "mrrg_base.json": json.dumps(
            architecture.mrrg_payload(configuration), indent=2,
            sort_keys=True) + "\n",
        reports / "modulo_mapping_graphs.json": json.dumps(
            mmg.payload(), indent=2, sort_keys=True) + "\n",
        reports / "scheduled_context_library.json": json.dumps(
            compiled_contexts, indent=2, sort_keys=True) + "\n",
        reports / "m3_control_image.json": json.dumps(
            m3_control_image.payload(), indent=2, sort_keys=True) + "\n",
        reports / "m11_program_images.json": json.dumps(
            m11_program_images.payload(), indent=2, sort_keys=True) + "\n",
        reports / "m11_program_readiness.json": json.dumps(
            m11_program_images.readiness_payload(), indent=2,
            sort_keys=True) + "\n",
        ROOT / "verification" / "v3" / "m3" / "generated" /
        "m3_control_image.vh": m3_control_image.sv_include(),
    }
    for name, content in context_compiler.mem_files(compiled_contexts).items():
        outputs[reports / "context_images" / name] = content
    for name, content in m11_program_images.mem_files().items():
        outputs[reports / "context_images" / name] = content
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    authority = [
        ROOT / "compiler" / "v3" / "generate_architecture_package.py",
        ROOT / "compiler" / "v3" / "architecture_scaling.py",
        ROOT / "compiler" / "v3" / "architecture_configuration.py",
        ROOT / "compiler" / "v3" / "architecture_configuration.json",
        ROOT / "compiler" / "v3" / "context_isa.py",
        ROOT / "compiler" / "v3" / "modulo_mapping_graph.py",
        ROOT / "compiler" / "v3" / "m11_program_images.py",
        ROOT / "compiler" / "v3" / "reconstruction_graphs.py",
        ROOT / "compiler" / "v3" / "run_configuration.py",
        ROOT / "compiler" / "v3" / "scheduled_context_compiler.py",
        ROOT / "models" / "v3" / "hardware.py",
    ]
    manifest = {
        "schema": "cscgra-v3-m36-architecture-manifest-v1",
        "architecture_configuration_sha256": architecture.configuration_hash(configuration),
        "context_revision": isa.CONTEXT_FORMAT_REVISION,
        "run_configuration_revision": run_configuration.REVISION,
        "macroblocks": graphs.payload()["architecture"]["macroblocks"],
        "authority_sha256": {str(p.relative_to(ROOT)).replace("\\", "/"): digest(p)
                             for p in authority},
        "generated_sha256": {str(p.relative_to(ROOT)).replace("\\", "/"): digest(p)
                             for p in outputs},
    }
    (reports / "architecture_manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")

def main() -> None:
    argparse.ArgumentParser().parse_args()
    generate()
    print("generated v3 M3.6 architecture package")

if __name__ == "__main__":
    main()
